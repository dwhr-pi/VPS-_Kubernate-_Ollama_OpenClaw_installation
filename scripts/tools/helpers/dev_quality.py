"""Optional Black/mypy builds from pinned GitHub sources; no project execution."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

from find_skills import checked, operation, resources
from offload_sources import fetch, verify

TOOLS = {
    "black": {"name": "Black", "url": "https://github.com/psf/black.git",
              "pin": "258e7dbf348bc23cb70b8cdf693481c04634ebcc", "version": "26.10.1",
              "module": "src/black/__init__.py",
              "files": ("LICENSE", "pyproject.toml", "src/black/__init__.py")},
    "mypy": {"name": "Mypy", "url": "https://github.com/python/mypy.git",
             "pin": "935ba8afba7ceacca0651579450c74339f343016", "version": "2.4.0",
             "module": "mypy/__init__.py",
             "files": ("LICENSE", "pyproject.toml", "setup.py", "mypy/__init__.py")},
}


def paths(tool):
    raw = Path(os.environ.get("OPENCLAW_USER_DATA_DIR", str(Path.home() / ".openclaw_ultimate_user_data")))
    if not raw.is_absolute() or raw == Path(raw.anchor):
        raise ValueError("Absoluten externen User-Workspace angeben, nicht die Dateisystemwurzel.")
    base = checked(raw / "tools" / tool)
    return base, checked(base / "source"), checked(base / "build-ready.json")


def python_in(environment):
    return checked(environment / ("Scripts/python.exe" if os.name == "nt" else "bin/python"))


def digest(path):
    checksum = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024**2), b""):
            checksum.update(chunk)
    return checksum.hexdigest()


def inventory(root):
    """Hash owned files; generated bytecode is disposable, internal links stay bounded."""
    result = {}
    for folder, dirs, files in os.walk(root, followlinks=False):
        dirs[:] = [name for name in dirs if name != "__pycache__"]
        for name in sorted(dirs + files):
            path = Path(folder) / name
            rel = path.relative_to(root).as_posix()
            if path.is_symlink():
                if not path.resolve().is_relative_to(root.resolve()):
                    raise ValueError("Link ausserhalb eigener Python-Umgebung; nichts loeschen.")
                result[rel] = "link:" + os.readlink(path)
            elif checked(path).is_dir():
                result[rel] = "directory"
            elif path.is_file():
                if path.suffix != ".pyc":
                    result[rel] = digest(path)
            else:
                raise ValueError("Unbekannte Spezialdatei in Python-Umgebung; nichts loeschen.")
    return result


def record_ok(base, marker, spec):
    data = json.loads(marker.read_text(encoding="utf-8"))
    if (not isinstance(data, dict) or data.get("commit") != spec["pin"] or
            data.get("version") != spec["version"] or data.get("scope") != "github-source-installed" or
            data.get("project_tested") is not False or
            not re.fullmatch(r"env-[A-Za-z0-9_-]+", str(data.get("environment", ""))) or
            not isinstance(data.get("hashes"), dict) or not data["hashes"]):
        raise ValueError("Unbekannter Besitznachweis; keine Dateien ersetzen oder loeschen.")
    environment = checked(base / data["environment"])
    if not python_in(environment).is_file() or inventory(environment) != data["hashes"]:
        raise ValueError("Python-Umgebung fehlt/veraendert; persoenliche Dateien bleiben erhalten.")
    return environment


def build_env(base, tool, spec):
    keep = ("PATH", "SystemRoot", "SYSTEMROOT", "WINDIR", "COMSPEC", "PATHEXT", "LANG")
    env = {key: os.environ[key] for key in keep if key in os.environ}
    home, tmp = checked(base / "build-home"), checked(base / "build-temp")
    home.mkdir(exist_ok=True, mode=0o700)
    tmp.mkdir(exist_ok=True, mode=0o700)
    env.update(HOME=str(home), USERPROFILE=str(home), TMPDIR=str(tmp), TMP=str(tmp), TEMP=str(tmp),
               PIP_CONFIG_FILE=os.devnull, PIP_INDEX_URL="https://pypi.org/simple",
               PIP_DISABLE_PIP_VERSION_CHECK="1", PIP_NO_INPUT="1", PIP_NO_CACHE_DIR="1",
               PYTHONNOUSERSITE="1", PYTHONDONTWRITEBYTECODE="1", MYPY_USE_MYPYC="0",
               HATCH_BUILD_HOOKS_ENABLE="0", CMAKE_BUILD_PARALLEL_LEVEL="1", MAX_JOBS="1",
               SETUPTOOLS_SCM_PRETEND_VERSION=spec["version"])
    if tool == "black":
        env["SETUPTOOLS_SCM_PRETEND_VERSION_FOR_BLACK"] = spec["version"]
    return env


def run(command, cwd, env, timeout=1800, capture=False):
    kwargs = {"capture_output": True, "text": True} if capture else {
        "stdout": sys.stdout.log, "stderr": subprocess.STDOUT}
    try:
        return subprocess.run(command, cwd=cwd, env=env, check=True, timeout=timeout, **kwargs)
    except (OSError, subprocess.SubprocessError):
        raise ValueError("Python-/Buildphase fehlgeschlagen oder Zeitlimit erreicht; siehe aktuelles Log. Kein System-Umbau.") from None


def budget(base):
    resources(base, base)
    if shutil.disk_usage(base).free < 2048 * 1024**2:
        raise ValueError("Speicherplatzmangel: mindestens 2 GiB freie Ziel-Disk erforderlich.")
    if os.environ.get("WSL_DISTRO_NAME") and Path("/mnt/c").is_dir():
        if shutil.disk_usage("/mnt/c").free < 2048 * 1024**2:
            raise ValueError("Speicherplatzmangel: Windows-C:-Reserve mindestens 2 GiB.")


def install(tool, base, source, marker, spec):
    if marker.exists():
        record_ok(base, marker, spec)
        verify(source, spec)
        print("Bereits installiert; derselbe Pin, kein automatisches latest-Upgrade.")
        return
    budget(base)
    if not (3, 10) <= sys.version_info[:2] <= (3, 15):
        raise ValueError("Python 3.10-3.15 mit venv/ensurepip/SSL erforderlich; DEV_QUALITY_PYTHON_BIN setzen.")
    env = build_env(base, tool, spec)
    run([sys.executable, "-I", "-c", "import venv, ensurepip, ssl"], base, env, 30)
    fetch(base, source, spec)
    environment = checked(Path(tempfile.mkdtemp(prefix="env-", dir=base)))
    published = False
    try:
        run([sys.executable, "-I", "-m", "venv", "--copies", str(environment)], base, env, 180)
        python = str(python_in(environment))
        with tempfile.TemporaryDirectory(prefix="build-source-", dir=base) as scratch:
            # Build hooks may mutate their checkout; preserve the verified source cache.
            build_source = Path(scratch) / "source"
            shutil.copytree(source, build_source, symlinks=True)
            run([python, "-I", "-m", "pip", "install", "--no-input", "--no-cache-dir",
                 "--index-url", "https://pypi.org/simple", "--only-binary=:all:", str(build_source)], base, env)
        run([python, "-I", "-m", "pip", "check"], base, env, 60)
        probe = ("import importlib.metadata as m; "
                 f"assert m.version({tool!r}) == {spec['version']!r}")
        run([python, "-I", "-B", "-c", probe], base, env, 30)
        print("Installierte transitive Versionen (kein eingefrorener Dependency-Lock):")
        run([python, "-I", "-m", "pip", "freeze", "--exclude-editable"], base, env, 60)
        data = {"commit": spec["pin"], "version": spec["version"], "scope": "github-source-installed",
                "environment": environment.name, "hashes": inventory(environment), "project_tested": False}
        fd, pending = tempfile.mkstemp(prefix="marker-", dir=base)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as output:
                json.dump(data, output)
            os.replace(pending, marker)
            published = True
        finally:
            Path(pending).unlink(missing_ok=True)
        print(spec["name"], "aus GitHub installiert. Keine Projektpruefung/Formatierung gestartet.")
        print("Bewusste Nutzung:", python, "-B -m", tool, "--help")
    finally:
        if not published:
            shutil.rmtree(checked(environment))
            print("Rollback: nur neue private Python-Umgebung entfernt; Quellen und Logs bleiben erhalten.")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tool", choices=TOOLS)
    parser.add_argument("action", nargs="?", default="install",
                        choices=("install", "update", "repair", "uninstall", "status", "check", "doctor", "plan"))
    parser.add_argument("--dry-run", action="store_true")
    modes = parser.add_mutually_exclusive_group()
    for mode in ("check", "repair", "uninstall", "status"):
        modes.add_argument("--" + mode, dest="override", action="store_const", const=mode)
    opts = parser.parse_args(argv)
    if opts.override:
        if opts.action not in ("install", opts.override):
            parser.error("Widerspruechliche Aktionen; nichts veraendert.")
        opts.action = opts.override
    spec = TOOLS[opts.tool]
    base, source, marker = paths(opts.tool)
    if opts.dry_run or opts.action == "plan":
        print(spec["name"], "GitHub:", spec["url"], "Pin:", spec["pin"], "Ziel:", base)
        print("Privates venv; 2 GiB Disk, kein Docker/sudo/apt, keine Dienste oder Projektlaeufe.")
        print("Build-/Runtime-Abhaengigkeiten: PyPI; keine Source-Builds transitiver Pakete.")
        return 0
    if opts.action in ("status", "check", "doctor"):
        ready = False
        try:
            record_ok(base, marker, spec)
            verify(source, spec)
            ready = True
        except (ValueError, OSError, subprocess.SubprocessError):
            pass
        print(json.dumps({"installed": ready, "project_tested": False}))
        return 0 if ready or opts.action == "status" else 1
    with operation(base, opts.action, tool=spec["name"]):
        print("Quelle:", spec["url"], "Pin:", spec["pin"], "Version:", spec["version"])
        if opts.action == "uninstall":
            if marker.exists():
                environment = record_ok(base, marker, spec)
                # Remove registration before deleting files; partial failures are not installed.
                marker.unlink()
                shutil.rmtree(environment)
            print("Eigene Python-Umgebung entfernt; Quellen/Logs und fremde Installationen bleiben erhalten.")
        else:
            install(opts.tool, base, source, marker, spec)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.SubprocessError) as exc:
        print("Dev-Quality:", exc, file=sys.stderr)
        sys.exit(1)
